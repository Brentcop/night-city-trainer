// The Home page is in the entry chunk, so it bundles only what its first paint needs: the deck library, cards,
// ratings, seasons and the round robin. The recommended deck's finals and head-to-heads (deckReports.json, ~110 KB)
// load at runtime (useDeckReports); their tile keeps its place with a placeholder until then.
import { useEffect, useState } from 'react';
import '../deckprofile.css';
import { RATINGS, SEASONS } from '../../data/index';
import type { DeckReports } from '../../data/deckReportsData';
import { RECOMMENDATION } from '../../content/recommendation';
import { EVENT } from '../../content/event';
import { allDecks } from '../../lib/browserLibrary';
import type { LibraryDeck } from '../../lib/library';
import { bredInfo, deckStats, pct } from '../../lib/deckStats';
import { DeckTile, LegendStrip, OriginBadge, ColorPips } from '../components/DeckIdentity';
import { Markdown } from '../components/Markdown';
import { ok, profileHref, StatTile, WrBar } from '../components/DeckStats';

type ReportsModule = typeof import('../../data/deckReportsData');
let reportsLoad: Promise<ReportsModule | null> | null = null;
/** deckReports.json, loaded once on first use (null if its chunk could not be fetched). Kept out of the entry chunk. */
export function loadDeckReports(): Promise<ReportsModule | null> {
  reportsLoad ??= import('../../data/deckReportsData').catch(() => {
    reportsLoad = null; // let a later visit try again
    return null;
  });
  return reportsLoad;
}
/** A deck file's reports: undefined while loading, {} if none (or the data could not be loaded). */
function useDeckReports(file: string): DeckReports | undefined {
  const [rep, setRep] = useState<{ file: string; rep: DeckReports } | null>(null);
  useEffect(() => {
    let live = true;
    loadDeckReports().then((m) => live && setRep({ file, rep: m ? m.deckReports(file) : {} }));
    return () => {
      live = false;
    };
  }, [file]);
  return rep?.file === file ? rep.rep : undefined;
}

function Countdown() {
  const [now, setNow] = useState(Date.now());
  useEffect(() => {
    const t = setInterval(() => setNow(Date.now()), 60_000);
    return () => clearInterval(t);
  }, []);
  const ms = EVENT.start.getTime() - now;
  if (ms <= 0) return <span className="countdown">Event underway</span>;
  const d = Math.floor(ms / 86_400_000);
  const h = Math.floor((ms % 86_400_000) / 3_600_000);
  return (
    <span className="countdown">
      {d}d {h}h
    </span>
  );
}

// The recommendation is generated by scripts/plan.ts; its first bold name is the pick and "Backup: **X**" the backup.
// Fallback (if the generated text changes shape): the S2-08 Explorer (RRG) pick from the 2026-11-10 finals.
const FALLBACK_PICK = 's2-08-explorer-rrg.txt';
function recommended(lib: readonly LibraryDeck[]) {
  const name = RECOMMENDATION.match(/\*\*([^*]+)\*\*/)?.[1];
  const backupName = RECOMMENDATION.match(/Backup: \*\*([^*]+)\*\*/)?.[1];
  const pick = lib.find((d) => d.deck.name === name) ?? lib.find((d) => d.file === FALLBACK_PICK);
  return { pick, backup: lib.find((d) => d.deck.name === backupName) };
}

function RecommendedHero({ d, backup, lib }: { d: LibraryDeck; backup?: LibraryDeck; lib: readonly LibraryDeck[] }) {
  return <RecommendedHeroView d={d} backup={backup} lib={lib} rep={useDeckReports(d.file)} />;
}

/** The hero itself; `rep` undefined = the deck's reports are still loading (a placeholder tile keeps the finals' place). */
export function RecommendedHeroView({ d, backup, lib, rep }: { d: LibraryDeck; backup?: LibraryDeck; lib: readonly LibraryDeck[]; rep: DeckReports | undefined }) {
  const st = deckStats(d.file);
  const bred = bredInfo(d.deck.name);
  const slug = d.file.replace(/\.txt$/, '');
  const build = lib.find((x) => x.file === `${slug}-eor.txt`);
  const loading = rep === undefined;
  const finals = rep?.finals?.overall ?? st.leader?.finals;
  const tips = RECOMMENDATION.split('\n')
    .filter((l) => l.startsWith('- '))
    .slice(0, 1) // keep Home short: seat advice only; the rest is on the deck profile
    .join('\n');
  const h2h = (rep?.h2h ?? []).slice().sort((a, b) => a.opp.localeCompare(b.opp));
  return (
    <div className="rec-hero">
      <LegendStrip legends={d.deck.legends} height={190} />
      <div className="rec-hero-body">
        <div className="rec-kicker">RECOMMENDED DECK FOR THE EVENT</div>
        <div className="row">
          <OriginBadge deck={d} full />
          <ColorPips legends={d.deck.legends} />
          {st.leader && <span className="tag">{st.leader.arch}</span>}
        </div>
        <h2 className="dp-title" style={{ fontSize: 'clamp(1.5rem, 4.5vw, 2.2rem)' }}>
          {d.deck.name}
        </h2>
        {bred && (
          <div className="small muted">
            Bred in Season {bred.season} by the trainer’s deck breeder.
          </div>
        )}
        <div className="dp-tiles">
          {loading ? (
            <div className="dp-tile is-loading" aria-hidden="true">
              <div className="dp-tile-val">&nbsp;</div>
              <div className="dp-tile-label">Finals vs meta</div>
              <div className="dp-tile-cap">&nbsp;</div>
            </div>
          ) : (
            ok(finals) && <StatTile value={pct(finals)} label="Finals vs meta" caption={rep.finals ? `${rep.finals.games} deep-bot games vs the meta archetypes` : undefined} />
          )}
          {st.leader && ok(st.leader.rating) && (
            <StatTile value={pct(st.leader.rating)} label="All-time rating" caption={`#${st.leader.rank} of ${st.leader.of}${ok(st.leader.percentile) ? ` · ${st.leader.percentile}th percentile` : ''}`} />
          )}
        </div>
        {h2h.length > 0 && (
          <div className="dp-bars">
            <div className="small muted">Head-to-heads vs the top meta threats</div>
            {h2h.map((r) => (
              <div key={r.opp} className="dp-bar-row">
                <span className="dp-bar-name" title={r.opp}>
                  vs {r.opp}
                </span>
                <WrBar v={r.w} title={`${pct(r.w, 1)} over ${r.g} games`} />
                <span className="dp-bar-val">{pct(r.w)}</span>
                <span className="dp-bar-sub">{r.g} games · on the play {r.fg ? `${Math.round((100 * r.fw) / r.fg)}%` : '—'} · on the draw {r.sg ? `${Math.round((100 * r.sw) / r.sg)}%` : '—'}</span>
              </div>
            ))}
          </div>
        )}
        {tips && <Markdown text={tips} />}
        <div className="row">
          <a className="rec-see" href={profileHref(d.file)}>
            See full stats →
          </a>
          <a className="btn" href={`#/play?d=${encodeURIComponent((build ?? d).file)}`}>
            ▶ Practice with it
          </a>
          <a className="btn" href="#/guides">
            Tournament plan
          </a>
        </div>
        <div className="small muted">
          {build && (
            <>
              Ready to register: <a href={profileHref(build.file)}>{build.deck.name}</a> (adds a data-chosen sideboard).{' '}
            </>
          )}
          {backup && (
            <>
              Backup: <a href={profileHref(backup.file)}>{backup.deck.name}</a>.
            </>
          )}
        </div>
      </div>
    </div>
  );
}

export function Home() {
  const lib = allDecks();
  const { pick, backup } = recommended(lib);
  // Top 5: power ratings from the tournament series when available, else the season leaderboard
  const fromRatings = RATINGS.decks.map((r) => lib.find((d) => d.deck.name === r.name)).filter((d): d is LibraryDeck => !!d);
  const fromSeasons = SEASONS.leaderboard.map((r) => lib.find((d) => d.file === r.file)).filter((d): d is LibraryDeck => !!d);
  const top = (fromRatings.length ? fromRatings : fromSeasons).slice(0, 5);
  return (
    <div className="grid">
      <div className="event-bar">
        <div>
          <span className="muted small">NEXT EVENT</span> <b>{EVENT.name}</b> <span className="muted small">· Dec 11–13 · Bo3 Swiss</span>
        </div>
        <Countdown />
      </div>

      {pick && <RecommendedHero d={pick} backup={backup} lib={lib} />}

      <div className="quick-actions">
        {[
          ['▶', 'Practice', 'Play the recommended deck against the bot, with a coach.', `#/play?d=${encodeURIComponent(pick?.file ?? '')}`],
          ['▤', 'Browse decks', 'Every deck with its origin, art and full stats.', '#/decks'],
          ['🏆', 'Tournaments', 'Brackets, standings and replays of every simulated event.', '#/tournaments'],
        ].map(([icon, t, d, href]) => (
          <a key={t} href={href} className="quick-action flair">
            <span className="qa-icon">{icon}</span>
            <b>{t}</b>
            <span className="muted small">{d}</span>
          </a>
        ))}
      </div>

      {top.length > 0 && (
        <div className="panel flair">
          <div className="spread" style={{ padding: 0, flexWrap: 'wrap' }}>
            <h2 style={{ margin: 0 }}>{fromRatings.length ? 'Top 5 by power rating' : 'All-time leaderboard'}</h2>
            <a className="small" href={fromRatings.length ? '#/ratings' : '#/seasons'}>
              See all →
            </a>
          </div>
          <div className="deck-grid" style={{ marginTop: 8 }}>
            {top.map((d) => (
              <DeckTile key={d.file} d={d} href={profileHref(d.file)} />
            ))}
          </div>
        </div>
      )}
    </div>
  );
}
