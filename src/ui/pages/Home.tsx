const EVENT = { name: 'Edgerunner Open Regional — Chicago', start: new Date('2026-12-11T09:00:00-06:00'), url: 'https://cyberpunktcg.com/eor' };

function Countdown() {
  const [now, setNow] = useState(Date.now());
  useEffect(() => {
    const t = setInterval(() => setNow(Date.now()), 60_000);
    return () => clearInterval(t);
  }, []);
  const ms = EVENT.start.getTime() - now;
  if (ms <= 0) return <span className="countdown">Event underway</span>;
  const d = Math.floor(ms / 86_400_000);
  const h = Math.floor((ms % 86_400_000) / 3_600_000);
  return (
    <span className="countdown">
      {d}d {h}h
    </span>
  );
}

// The recommendation is generated by scripts/plan.ts; its first bold name is the pick and "Backup: **X**" the backup.
// Fallback (if the generated text changes shape): the S2-08 Explorer (RRG) pick from the 2026-11-10 finals.
const FALLBACK_PICK = 's2-08-explorer-rrg.txt';
function recommended(lib: LibraryDeck[]) {
  const name = RECOMMENDATION.match(/\*\*([^*]+)\*\*/)?.[1];
  const backupName = RECOMMENDATION.match(/Backup: \*\*([^*]+)\*\*/)?.[1];
  const pick = lib.find((d) => d.deck.name === name) ?? lib.find((d) => d.file === FALLBACK_PICK);
  return { pick, backup: lib.find((d) => d.deck.name === backupName) };
}

function RecommendedHero({ d, backup, lib }: { d: LibraryDeck; backup?: LibraryDeck; lib: LibraryDeck[] }) {
  const st = deckStats(d.file);
  const rep = deckReports(d.file);
  const bred = bredInfo(d.deck.name);
  const slug = d.file.replace(/\.txt$/, '');
  const build = lib.find((x) => x.file === `${slug}-eor.txt`);
  const finals = rep.finals?.overall ?? st.leader?.finals;
  const tips = RECOMMENDATION.split('\n')
    .filter((l) => l.startsWith('- '))
    .join('\n');
  const h2h = (rep.h2h ?? []).slice().sort((a, b) => a.opp.localeCompare(b.opp));
  return (
    <div className="rec-hero">
      <LegendStrip legends={d.deck.legends} height={260} />
      <div className="rec-hero-body">
        <div className="rec-kicker">RECOMMENDED DECK FOR THE EVENT</div>
        <div className="row">
          <OriginBadge deck={d} full />
          <ColorPips legends={d.deck.legends} />
          {st.leader && <span className="tag">{st.leader.arch}</span>}
        </div>
        <h2 className="dp-title" style={{ fontSize: 'clamp(1.5rem, 4.5vw, 2.2rem)' }}>
          {d.deck.name}
        </h2>
        {bred && (
          <div className="small muted">
            Bred in Season {bred.season} by the trainer’s automated breeder ({bred.method}). Picked by the tournament plan from the finals against the choom.gg meta decks (see the Strategy page for why).
          </div>
        )}
        <div className="dp-tiles">
          {ok(finals) && <StatTile value={pct(finals)} label="Finals vs meta" caption={rep.finals ? `${rep.finals.games} deep-bot games vs the meta archetypes` : undefined} />}
          {st.leader && ok(st.leader.rating) && (
            <StatTile value={pct(st.leader.rating)} label="All-time rating" caption={`#${st.leader.rank} of ${st.leader.of}${ok(st.leader.percentile) ? ` · ${st.leader.percentile}th percentile` : ''}`} />
          )}
        </div>
        {h2h.length > 0 && (
          <div className="dp-bars">
            <div className="small muted">Head-to-heads vs the top meta threats</div>
            {h2h.map((r) => (
              <div key={r.opp} className="dp-bar-row">
                <span className="dp-bar-name" title={r.opp}>
                  vs {r.opp}
                </span>
                <WrBar v={r.w} title={`${pct(r.w, 1)} over ${r.g} games`} />
                <span className="dp-bar-val">{pct(r.w)}</span>
                <span className="dp-bar-sub">{r.g} games · on the play {r.fg ? `${Math.round((100 * r.fw) / r.fg)}%` : '—'} · on the draw {r.sg ? `${Math.round((100 * r.sw) / r.sg)}%` : '—'}</span>
              </div>
            ))}
          </div>
        )}
        {tips && <Markdown text={tips} />}
        <div className="row">
          <a className="rec-see" href={profileHref(d.file)}>
            See full stats →
          </a>
          <a href={`#/play?d=${encodeURIComponent((build ?? d).file)}`}>
            <button>▶ Practice with it</button>
          </a>
          <a href="#/guides">
            <button>Tournament plan</button>
          </a>
        </div>
        <div className="small muted">
          {build && (
            <>
              Ready to register: <a href={profileHref(build.file)}>{build.deck.name}</a> (adds a data-chosen sideboard).{' '}
            </>
          )}
          {backup && (
            <>
              Backup: <a href={profileHref(backup.file)}>{backup.deck.name}</a>.
            </>
          )}
        </div>
      </div>
    </div>
  );
}

